import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const outputFile = path.join(rootDir, "lib", "engine", "engine-version.ts");
const searchDirs = [
  path.join(rootDir, "lib", "rules"),
  path.join(rootDir, "lib", "engine")
];

function collectFiles(dir) {
  if (!fs.existsSync(dir)) {
    return [];
  }
  const results = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      results.push(...collectFiles(fullPath));
    } else if (entry.isFile()) {
      if (path.resolve(fullPath) === path.resolve(outputFile)) {
        continue;
      }
      results.push(fullPath);
    }
  }
  return results;
}

const allFiles = [];
for (const dir of searchDirs) {
  allFiles.push(...collectFiles(dir));
}

allFiles.sort((a, b) => {
  const relA = path.relative(rootDir, a).split(path.sep).join("/");
  const relB = path.relative(rootDir, b).split(path.sep).join("/");
  return relA.localeCompare(relB);
});

const hash = crypto.createHash("sha256");
for (const file of allFiles) {
  const relPath = path.relative(rootDir, file).split(path.sep).join("/");
  hash.update(relPath);
  hash.update("\0");
  hash.update(fs.readFileSync(file));
  hash.update("\0");
}

const engineVersion = hash.digest("hex");

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
const content = `// Generated by scripts/generate-engine-version.mjs. Do not edit directly.\nexport const engineVersion = "${engineVersion}";\nexport const ENGINE_VERSION = engineVersion;\n`;
fs.writeFileSync(outputFile, content, "utf8");
console.log(
  `Generated engineVersion: ${engineVersion} -> ${path.relative(rootDir, outputFile)}`
);
