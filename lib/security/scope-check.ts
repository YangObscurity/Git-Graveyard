// Task 11.2: Candidate diff validation and scope check
// Requirements: 22.12, 640.3, 732.13, 616.3

import * as Diff from "diff";
import * as path from "node:path";

export const SUPPORTED_LOCK_FILES = [
  "package-lock.json",
  "npm-shrinkwrap.json",
  "yarn.lock",
  "pnpm-lock.yaml",
  "poetry.lock",
  "Pipfile.lock",
] as const;

export type SupportedLockFileName = (typeof SUPPORTED_LOCK_FILES)[number];
const LOCK_FILE_SET = new Set<string>(SUPPORTED_LOCK_FILES);

export type ScopeCheckViolationType = "forbidden_directory" | "out_of_scope";

export interface ScopeCheckViolation {
  readonly path: string;
  readonly rule: ScopeCheckViolationType;
  readonly message: string;
}

export interface ScopeCheckResult {
  readonly valid: boolean;
  readonly passed: boolean;
  readonly touchedFiles: readonly string[];
  readonly forbiddenPaths: readonly string[];
  readonly outOfScopePaths: readonly string[];
  readonly violations: readonly string[];
  readonly structuredViolations: readonly ScopeCheckViolation[];
  readonly reason?: string;
}

export interface CandidateInput {
  readonly diff?: string;
  readonly changedFiles?: readonly string[];
  readonly changed?: readonly string[];
  readonly files?: readonly string[] | Readonly<Record<string, unknown>>;
  readonly steps?: readonly { readonly file?: string }[];
  readonly [key: string]: unknown;
}

export interface ScopeCheckOptions {
  readonly filesInScope?: readonly string[];
  readonly taskFiles?: readonly string[];
  readonly allowedFiles?: readonly string[];
  readonly allowLockFiles?: boolean;
  readonly customLockFiles?: readonly string[];
  readonly customForbiddenPatterns?: readonly (string | RegExp)[];
}

/**
 * Normalizes a candidate file path, removing git diff prefixes (a/, b/) and leading/trailing slashes.
 */
export function normalizeDiffPath(rawPath: string): string {
  if (!rawPath || typeof rawPath !== "string") {
    return "";
  }
  let p = rawPath.replace(/\\/g, "/").trim();
  if (p === "/dev/null" || p === "dev/null") {
    return "";
  }
  p = p.replace(/^[ab]\//, "");
  while (p.startsWith("./")) {
    p = p.slice(2);
  }
  p = p.replace(/^\/+/, "");
  p = p.replace(/\/+$/, "");
  p = path.posix.normalize(p);
  while (p.startsWith("./")) {
    p = p.slice(2);
  }
  p = p.replace(/^\/+/, "");
  if (p === "." || p === "./" || p === "dev/null" || p === "/dev/null") {
    return "";
  }
  return p;
}

/**
 * Checks whether a file path touches .kiro/ or .git/.
 * Strictly forbids any modification inside .kiro/ or .git/.
 * Does not match .gitignore, .gitattributes, .github, or .kiro-runs.
 */
export function isForbiddenPath(filePath: string): boolean {
  const norm = normalizeDiffPath(filePath);
  if (!norm) return false;

  const segments = norm.split("/");
  for (const seg of segments) {
    if (seg === ".kiro" || seg === ".git") {
      return true;
    }
  }

  return false;
}

export const isForbiddenCandidatePath = isForbiddenPath;

/**
 * Checks whether a path corresponds to an allowed dependency lock file generated by package manager installs.
 * Per Requirement 640.3, lock files generated by installs are permitted even if outside explicit task scope.
 */
export function isLockFile(filePath: string, customLockFiles?: readonly string[]): boolean {
  const norm = normalizeDiffPath(filePath);
  if (!norm) return false;

  const base = path.posix.basename(norm);
  if (customLockFiles && customLockFiles.length > 0) {
    const customSet = new Set(customLockFiles);
    if (customSet.has(base)) return true;
  }

  return LOCK_FILE_SET.has(base as SupportedLockFileName);
}

/**
 * Extracts all touched file paths from a unified diff string.
 * Strips git prefixes (a/, b/) and ignores /dev/null.
 */
export function extractTouchedFilesFromDiff(diff: string): string[] {
  if (!diff || typeof diff !== "string" || !diff.trim()) {
    return [];
  }

  const touchedSet = new Set<string>();

  try {
    const patches = Diff.parsePatch(diff);
    for (const patch of patches) {
      if (patch.oldFileName && patch.oldFileName !== "/dev/null") {
        const cleanOld = normalizeDiffPath(patch.oldFileName);
        if (cleanOld) touchedSet.add(cleanOld);
      }
      if (patch.newFileName && patch.newFileName !== "/dev/null") {
        const cleanNew = normalizeDiffPath(patch.newFileName);
        if (cleanNew) touchedSet.add(cleanNew);
      }
    }
  } catch {
    // Fallback to regex diff parsing if Diff.parsePatch fails
    const diffHeaderRegex = /(?:^diff --git a\/(\S+) b\/(\S+)|^--- (?:a\/)?(\S+)|^\+\+\+ (?:b\/)?(\S+))/gm;
    let match: RegExpExecArray | null;
    while ((match = diffHeaderRegex.exec(diff)) !== null) {
      const p1 = match[1];
      const p2 = match[2];
      const p3 = match[3];
      const p4 = match[4];

      for (const raw of [p1, p2, p3, p4]) {
        if (raw && raw !== "/dev/null") {
          const clean = normalizeDiffPath(raw);
          if (clean) touchedSet.add(clean);
        }
      }
    }
  }

  return Array.from(touchedSet).sort();
}

/**
 * Extracts all touched file paths from a candidate input, which can be a diff string or CandidateInput object.
 */
export function extractTouchedFiles(input: string | CandidateInput): string[] {
  if (typeof input === "string") {
    return extractTouchedFilesFromDiff(input);
  }

  const touchedSet = new Set<string>();

  if (typeof input.diff === "string" && input.diff.trim()) {
    const fromDiff = extractTouchedFilesFromDiff(input.diff);
    for (const f of fromDiff) touchedSet.add(f);
  }

  const explicitChanged = input.changedFiles ?? input.changed;
  if (Array.isArray(explicitChanged)) {
    for (const f of explicitChanged) {
      if (typeof f === "string") {
        const clean = normalizeDiffPath(f);
        if (clean) touchedSet.add(clean);
      }
    }
  }

  if (Array.isArray(input.files)) {
    for (const f of input.files) {
      if (typeof f === "string") {
        const clean = normalizeDiffPath(f);
        if (clean) touchedSet.add(clean);
      }
    }
  } else if (input.files && typeof input.files === "object") {
    for (const k of Object.keys(input.files)) {
      const clean = normalizeDiffPath(k);
      if (clean) touchedSet.add(clean);
    }
  }

  if (Array.isArray(input.steps)) {
    for (const s of input.steps) {
      if (s && typeof s.file === "string") {
        const clean = normalizeDiffPath(s.file);
        if (clean) touchedSet.add(clean);
      }
    }
  }

  return Array.from(touchedSet).sort();
}

/**
 * Validates a list of touched candidate files against forbidden directory rules (.kiro/ and .git/)
 * and optional task scope file lists.
 */
export function validateCandidateFiles(
  touchedFiles: readonly string[],
  options?: ScopeCheckOptions
): ScopeCheckResult {
  const normTouched = Array.from(
    new Set(
      touchedFiles
        .map((f) => normalizeDiffPath(f))
        .filter((f) => f.length > 0)
    )
  ).sort();

  const violations: string[] = [];
  const structuredViolations: ScopeCheckViolation[] = [];
  const forbiddenPaths: string[] = [];
  const outOfScopePaths: string[] = [];

  // Check 1: Forbidden directory check (.kiro/ and .git/) - Requirement 22.12, 732.13
  for (const filePath of normTouched) {
    if (isForbiddenPath(filePath)) {
      forbiddenPaths.push(filePath);
      const msg = `Candidate diff touches forbidden path: "${filePath}" (.kiro/ and .git/ modifications are strictly rejected)`;
      violations.push(msg);
      structuredViolations.push({
        path: filePath,
        rule: "forbidden_directory",
        message: msg,
      });
    }
  }

  // Check 2: Task scope check - Requirement 640.3
  const allowedScopeList =
    options?.filesInScope ?? options?.taskFiles ?? options?.allowedFiles;

  if (allowedScopeList && Array.isArray(allowedScopeList)) {
    const scopeSet = new Set(
      allowedScopeList.map((f) => normalizeDiffPath(f)).filter(Boolean)
    );
    const allowLockFiles = options?.allowLockFiles !== false;

    for (const filePath of normTouched) {
      if (forbiddenPaths.includes(filePath)) {
        continue; // Already flagged as forbidden directory
      }

      const inScope = scopeSet.has(filePath);
      const isAllowedLock = allowLockFiles && isLockFile(filePath, options?.customLockFiles);

      if (!inScope && !isAllowedLock) {
        outOfScopePaths.push(filePath);
        const msg = `Candidate modifies file outside task scope: "${filePath}"`;
        violations.push(msg);
        structuredViolations.push({
          path: filePath,
          rule: "out_of_scope",
          message: msg,
        });
      }
    }
  }

  const isValid = violations.length === 0;

  return {
    valid: isValid,
    passed: isValid,
    touchedFiles: normTouched,
    forbiddenPaths: forbiddenPaths.sort(),
    outOfScopePaths: outOfScopePaths.sort(),
    violations,
    structuredViolations,
    reason: isValid
      ? undefined
      : `Scope check rejected: ${violations.join("; ")}`,
  };
}

/**
 * Validates a Candidate diff or Candidate object against scope rules.
 * Enforces Candidate diff validation rejecting any diff touching .kiro/ or .git/.
 */
export function validateCandidateDiff(
  diffOrCandidate: string | CandidateInput,
  options?: ScopeCheckOptions
): ScopeCheckResult {
  const touchedFiles = extractTouchedFiles(diffOrCandidate);
  return validateCandidateFiles(touchedFiles, options);
}

export const checkCandidateScope = validateCandidateDiff;
